"""Generate the screenshot sections of the READMEs (so no one hand-maintains a list of maps).

    python -m tools.readme            rewrite the generated blocks
    python -m tools.readme --check    exit 1 if any README is out of date (CI runs this)

Main README: the block between <!-- maps:start --> and <!-- maps:end --> gets a featured screenshot and a
table linking every map (from maps/*/map.toml: title, description, `hero` view, `featured = true`).
Map READMEs: the block between <!-- screenshots:start --> and <!-- screenshots:end --> (appended if missing)
gets every view from tests/views.py.

Images are the screenshots CI renders for main on every release (the `previews` branch, main/<map>/<view>.jpg),
so they stay current without committing images.
"""
import importlib.util
import re
import sys
import tomllib
from pathlib import Path

from tools.pipeline.gh import repo

ROOT = Path(__file__).resolve().parents[1]


def maps():
    out = []
    for d in sorted((ROOT / "maps").iterdir()):
        if not d.is_dir() or d.name.startswith("_") or not (d / "map.toml").exists():
            continue
        meta = tomllib.loads((d / "map.toml").read_text())
        spec = importlib.util.spec_from_file_location("views_%s" % d.name, d / "tests" / "views.py")
        mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
        views = [v[0] for v in mod.VIEWS]
        meta.update(dir=d.name, views=views, hero=meta.get("hero", views[0] if views else None))
        out.append(meta)
    return out


def img(name, view):
    return "https://raw.githubusercontent.com/%s/previews/main/%s/%s.jpg" % (repo(), name, view)


def replace_block(text, tag, body, append=False):
    start, end = "<!-- %s:start -->" % tag, "<!-- %s:end -->" % tag
    block = "%s\n<!-- generated by `make readme`: don't edit by hand -->\n%s\n%s" % (start, body.strip(), end)
    if start in text and end in text:
        return re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _: block, text, flags=re.S)
    if append:
        return text.rstrip() + "\n\n" + block + "\n"
    raise SystemExit("README has no %s ... %s markers" % (start, end))


def main_block(ms):
    feat = next((m for m in ms if m.get("featured")), ms[0] if ms else None)
    lines = []
    if feat:
        lines += ['<a href="maps/%s/"><img src="%s" alt="%s" width="100%%"></a>' % (feat["dir"], img(feat["dir"], feat["hero"]), feat["title"]), ""]
    lines += ["| | Map |", "|---|---|"]
    for m in ms:
        lines.append('| <a href="maps/%s/"><img src="%s" alt="%s" width="280"></a> | **[%s](maps/%s/)** (`%s`)<br>%s |'
                     % (m["dir"], img(m["dir"], m["hero"]), m["title"], m["title"], m["dir"], m["dir"], m.get("description", "")))
    return "\n".join(lines)


def map_block(m):
    lines = ["## Screenshots", "", "Rendered by CI from `main` after every release (preview renderer: see-through fences show as solid blue).", "",
             "| | |", "|---|---|"]
    v = m["views"]
    for i in range(0, len(v), 2):
        cells = ['<img src="%s" alt="%s" width="400"><br>`%s`' % (img(m["dir"], x), x, x) for x in v[i:i + 2]]
        lines.append("| %s |" % " | ".join(cells + [""] * (2 - len(cells))))
    return "\n".join(lines)


def run(check=False):
    ms = maps()
    files = {ROOT / "README.md": lambda t: replace_block(t, "maps", main_block(ms))}
    for m in ms:
        files[ROOT / "maps" / m["dir"] / "README.md"] = lambda t, m=m: replace_block(t, "screenshots", map_block(m), append=True)
    stale = []
    for path, fn in files.items():
        old = path.read_text() if path.exists() else "# %s\n" % path.parent.name
        new = fn(old)
        if new != old:
            stale.append(str(path.relative_to(ROOT)))
            if not check:
                path.write_text(new)
    if check and stale:
        print("README out of date (run `make readme`): " + ", ".join(stale)); return 1
    print(("updated: " + ", ".join(stale)) if stale and not check else "READMEs up to date")
    return 0


if __name__ == "__main__":
    sys.exit(run("--check" in sys.argv))
