package main

// The screenshot sections of the READMEs, generated so no one hand-maintains a list of maps.
//
// Main README: the block between <!-- maps:start --> and <!-- maps:end --> gets a featured screenshot and a
// table linking every map (from maps/*/map.toml: title, description, `hero` view, `featured = true`).
// Map READMEs: the block between <!-- screenshots:start --> and <!-- screenshots:end --> (appended if missing)
// gets every view from tests/views.py. Images are the screenshots CI renders for main on every release (the
// `previews` branch, main/<map>/<view>.jpg), so they stay current without committing images. Their URLs carry a
// version (`?v=<previews commit>`) so browsers fetch new images after `make readme V=<commit>`; without V the
// version already in README.md is kept.

import (
	"bufio"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

var errNoMarkers = errors.New("README has no generated-block markers")

var reImgVersion = regexp.MustCompile(`/previews/main/[^"?]+\.jpg\?v=([\w.-]+)`)

type mapMeta struct {
	dir, title, description, hero string
	featured                      bool
	views                         []string
}

// readToml reads the flat `key = "string"` / `key = true` lines map.toml uses.
func readToml(path string) (map[string]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close() //nolint:errcheck // read-only
	kv := map[string]string{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		k, v, ok := strings.Cut(line, "=")
		if !ok || strings.HasPrefix(line, "#") {
			continue
		}
		v = strings.TrimSpace(v)
		if s, err := strconv.Unquote(v); err == nil {
			v = s
		}
		kv[strings.TrimSpace(k)] = v
	}
	return kv, sc.Err()
}

// mapViewNames asks the map's own views.py (map scripts are Python) for its view names, in order.
func mapViewNames(root, name string) ([]string, error) {
	py := os.Getenv("PY")
	if py == "" {
		py = "python3"
	}
	cmd := exec.Command(py, "-m", "tools.render.views", name) //nolint:gosec // the interpreter the Makefile uses
	cmd.Dir = root
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("views of %s: %w", name, err)
	}
	var vs []json.RawMessage
	if err := json.Unmarshal(out, &vs); err != nil {
		return nil, err
	}
	names := make([]string, 0, len(vs))
	for _, v := range vs {
		var row []json.RawMessage
		var n string
		if err := json.Unmarshal(v, &row); err != nil || len(row) == 0 || json.Unmarshal(row[0], &n) != nil {
			return nil, fmt.Errorf("views of %s: bad entry %s", name, v) //nolint:err113 // names the entry
		}
		names = append(names, n)
	}
	return names, nil
}

func loadMaps(root string) ([]mapMeta, error) {
	var out []mapMeta
	for _, d := range subdirs(filepath.Join(root, "maps")) {
		name := filepath.Base(d)
		toml := filepath.Join(d, "map.toml")
		if strings.HasPrefix(name, "_") || !exists(toml) {
			continue
		}
		kv, err := readToml(toml)
		if err != nil {
			return nil, err
		}
		vs, err := mapViewNames(root, name)
		if err != nil {
			return nil, err
		}
		m := mapMeta{dir: name, title: kv["title"], description: kv["description"], hero: kv["hero"],
			featured: kv["featured"] == "true", views: vs}
		if m.hero == "" && len(vs) > 0 {
			m.hero = vs[0]
		}
		out = append(out, m)
	}
	return out, nil
}

func ghRepo(root string) string {
	if r := os.Getenv("GITHUB_REPOSITORY"); r != "" {
		return r
	}
	cmd := exec.Command("git", "remote", "get-url", "origin")
	cmd.Dir = root
	b, _ := cmd.Output()
	u := strings.TrimSuffix(strings.TrimRight(strings.TrimSpace(string(b)), "/"), ".git")
	if i := strings.LastIndex(u, "github.com"); i >= 0 {
		u = u[i+len("github.com"):]
	}
	return strings.TrimLeft(u, ":/")
}

func replaceBlock(text, tag, body string, appendIfMissing bool) (string, error) {
	start, end := "<!-- "+tag+":start -->", "<!-- "+tag+":end -->"
	block := start + "\n<!-- generated by `make readme`: don't edit by hand -->\n" + strings.TrimSpace(body) + "\n" + end
	if strings.Contains(text, start) && strings.Contains(text, end) {
		re := regexp.MustCompile(`(?s)` + regexp.QuoteMeta(start) + `.*?` + regexp.QuoteMeta(end))
		return re.ReplaceAllLiteralString(text, block), nil
	}
	if appendIfMissing {
		return strings.TrimRight(text, " \t\r\n\f\v") + "\n\n" + block + "\n", nil
	}
	return "", fmt.Errorf("%w: %s ... %s", errNoMarkers, start, end)
}

// imgURL is a screenshot on the previews branch, with the cache-busting version when there is one.
func imgURL(repo, dir, view, version string) string {
	u := fmt.Sprintf("https://raw.githubusercontent.com/%s/previews/main/%s/%s.jpg", repo, dir, view)
	if version != "" {
		u += "?v=" + version
	}
	return u
}

func mainBlock(repo, version string, ms []mapMeta) string {
	img := func(m mapMeta) string { return imgURL(repo, m.dir, m.hero, version) }
	var lines []string
	feat := -1
	for i, m := range ms {
		if m.featured {
			feat = i
			break
		}
	}
	if feat < 0 && len(ms) > 0 {
		feat = 0
	}
	if feat >= 0 {
		f := ms[feat]
		lines = append(lines, fmt.Sprintf(`<a href="maps/%s/"><img src="%s" alt="%s" width="100%%"></a>`, f.dir, img(f), f.title), "")
	}
	lines = append(lines, "| | Map |", "|---|---|")
	for _, m := range ms {
		lines = append(lines, fmt.Sprintf(`| <a href="maps/%s/"><img src="%s" alt="%s" width="280"></a> | **[%s](maps/%s/)** (`+"`%s`"+`)<br>%s |`,
			m.dir, img(m), m.title, m.title, m.dir, m.dir, m.description))
	}
	return strings.Join(lines, "\n")
}

func mapBlock(repo, version string, m mapMeta) string {
	lines := []string{"## Screenshots", "",
		"Rendered by CI from `main` after every release.", "",
		"| | |", "|---|---|"}
	for i := 0; i < len(m.views); i += 2 {
		var cells []string
		for _, v := range m.views[i:min(i+2, len(m.views))] {
			u := imgURL(repo, m.dir, v, version)
			cells = append(cells, fmt.Sprintf(`<img src="%s" alt="%s" width="400"><br>`+"`%s`", u, v, v))
		}
		for len(cells) < 2 {
			cells = append(cells, "")
		}
		lines = append(lines, "| "+strings.Join(cells, " | ")+" |")
	}
	return strings.Join(lines, "\n")
}

type readmeFile struct {
	path   string
	update func(string) (string, error)
}

func cmdReadme(root string, check bool, version string) (int, error) {
	ms, err := loadMaps(root)
	if err != nil {
		return 1, err
	}
	repo := ghRepo(root)
	if version == "" { // keep the version the README already uses
		if b, err := os.ReadFile(filepath.Join(root, "README.md")); err == nil {
			if m := reImgVersion.FindSubmatch(b); m != nil {
				version = string(m[1])
			}
		}
	}
	files := []readmeFile{{filepath.Join(root, "README.md"), func(t string) (string, error) {
		return replaceBlock(t, "maps", mainBlock(repo, version, ms), false)
	}}}
	for _, m := range ms {
		files = append(files, readmeFile{filepath.Join(root, "maps", m.dir, "README.md"), func(t string) (string, error) {
			return replaceBlock(t, "screenshots", mapBlock(repo, version, m), true)
		}})
	}
	var stale []string
	for _, f := range files {
		old := "# " + filepath.Base(filepath.Dir(f.path)) + "\n"
		if b, err := os.ReadFile(f.path); err == nil {
			old = string(b)
		}
		updated, err := f.update(old)
		if err != nil {
			return 1, err
		}
		if updated == old {
			continue
		}
		rel, _ := filepath.Rel(root, f.path)
		stale = append(stale, rel)
		if !check {
			if err := os.WriteFile(f.path, []byte(updated), 0o644); err != nil {
				return 1, err
			}
		}
	}
	switch {
	case check && len(stale) > 0:
		fmt.Println("README out of date (run `make readme`): " + strings.Join(stale, ", "))
		return 1, nil
	case len(stale) > 0:
		fmt.Println("updated: " + strings.Join(stale, ", "))
	default:
		fmt.Println("READMEs up to date")
	}
	return 0, nil
}
